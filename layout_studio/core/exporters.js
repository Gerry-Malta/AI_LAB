export const toJSON = (scene) => JSON.stringify(scene, null, 2);

const fmtV = (v) => `${v[0].toFixed(2)}, ${v[1].toFixed(2)}, ${v[2].toFixed(2)}`;

/** Blocking of the beat a shot belongs to. */
export function blockingFor(scene, shot) {
  const beat = (scene.beats || []).find((b) => b.id === shot.beat);
  return (beat && beat.blocking) || {};
}

/** Camera sheet: one row per shot, everything a DoP / key grip needs to reproduce the move. */
export function toCameraSheet(scene, evaluations = {}) {
  const lines = [];
  const sc = scene.scene || {};
  lines.push(`# Camera sheet — ${scene.project || ''} · Sc. ${sc.number ?? ''} ${sc.heading || ''}`.trim());
  lines.push('');
  lines.push(`Units: metres · positions as X, Y(up), Z · generated by Layout Studio`);
  lines.push('');
  lines.push('| Shot | Size | Subject | Lens | Rig / move | Dur | Key A (x,y,z) | Key B (x,y,z) | Dist to subject A→B | Notes |');
  lines.push('|---|---|---|---|---|---|---|---|---|---|');
  for (const shot of scene.shots || []) {
    const blocking = blockingFor(scene, shot);
    const subject = resolveSubject(scene, shot, blocking);
    const solved = solveShot(scene, shot);
    const A = shot.keys && shot.keys.A, B = (shot.keys && shot.keys.B) || A;
    const cam = Object.assign({ filmback: 'ALEXA35_OG', focal_mm: 35, aspect: 2.39 }, shot.camera || {});
    const notes = [];
    if (shot.dp && shot.dp.intent) notes.push(`DP intent: ${shot.dp.intent}${shot.dp.why && shot.dp.why[1] ? ` · ${shot.dp.why[1]}` : ''}`);
    if (shot.notes) notes.push(shot.notes);
    for (const w of solved.warnings) notes.push(`⚠ ${w}`);
    const ev = evaluations[shot.id];
    if (ev && ev.flags) for (const f of ev.flags) if (f.level !== 'info') notes.push(`${f.level === 'bad' ? '✖' : '⚠'} ${f.msg}`);
    lines.push(`| ${shot.name || shot.id} | ${shot.size || ''} | ${subject ? subject.name : ''} | ${lensLabel(cam)}${cam.fstop ? ` · T${cam.fstop}` : ''} | ${describeMove(solved.info)} | ${shot.duration_s || 0}s | ${A ? fmtV(A.position) : ''} h ${A ? A.position[1].toFixed(2) : ''} | ${B && B !== A ? fmtV(B.position) : '—'} | ${solved.info.distanceA ?? ''}${solved.info.distanceB != null && solved.info.distanceB !== solved.info.distanceA ? ` → ${solved.info.distanceB}` : ''} | ${notes.join('<br>')} |`);
  }
  lines.push('');
  lines.push('## Rig notes');
  lines.push('');
  lines.push('- Dolly: straight track unless a `via` point is set (curved track). Lens height = boom.');
  lines.push('- Crane: pivot on the ground, arm = distance pivot→lens. Swing/boom angles in the move column.');
  lines.push('- Steadicam / handheld / gimbal: operator path; speeds are walking speeds (≤ 1.6 m/s comfortable).');
  lines.push('- Static: sticks, pan/tilt only.');
  return lines.join('\n');
}

const py = (v) => `(${v.map((x) => (+x).toFixed(5)).join(', ')})`;
const C = (v) => [v[0], -v[2], v[1]]; // three (Y-up) -> Blender (Z-up)
const Cm = [[1, 0, 0], [0, 0, -1], [0, 1, 0]];
const CmT = mat3T(Cm);
const toBlenderRot = (R) => mat3Mul(mat3Mul(Cm, R), CmT);
const pyMat3 = (m) => `Matrix(((${m[0].join(', ')}), (${m[1].join(', ')}), (${m[2].join(', ')})))`;
const pyName = (s) => JSON.stringify(String(s));
const hexToRGB = (hex) => { const h = (hex || '#888888').replace('#', ''); const n = parseInt(h.length === 3 ? h.split('').map((c) => c + c).join('') : h, 16); return [((n >> 16) & 255) / 255, ((n >> 8) & 255) / 255, (n & 255) / 255]; };

function quatFromBasis(right, up, back) { // columns right, up, back(=-forward)
  const m00 = right[0], m01 = up[0], m02 = back[0], m10 = right[1], m11 = up[1], m12 = back[1], m20 = right[2], m21 = up[2], m22 = back[2];
  const tr = m00 + m11 + m22; let w, x, y, z;
  if (tr > 0) { const S = Math.sqrt(tr + 1) * 2; w = 0.25 * S; x = (m21 - m12) / S; y = (m02 - m20) / S; z = (m10 - m01) / S; }
  else if (m00 > m11 && m00 > m22) { const S = Math.sqrt(1 + m00 - m11 - m22) * 2; w = (m21 - m12) / S; x = 0.25 * S; y = (m01 + m10) / S; z = (m02 + m20) / S; }
  else if (m11 > m22) { const S = Math.sqrt(1 + m11 - m00 - m22) * 2; w = (m02 - m20) / S; x = (m01 + m10) / S; y = 0.25 * S; z = (m12 + m21) / S; }
  else { const S = Math.sqrt(1 + m22 - m00 - m11) * 2; w = (m10 - m01) / S; x = (m02 + m20) / S; y = (m12 + m21) / S; z = 0.25 * S; }
  return [w, x, y, z];
}

/** Camera pose (three space) -> Blender location + quaternion. */
export function cameraPoseToBlender(pose) {
  const eye = C(pose.position), tgt = C(pose.target);
  let f = norm(sub(tgt, eye));
  let r = norm(cross(f, [0, 0, 1])); if (!isFinite(r[0]) || Math.hypot(...r) < 1e-6) r = [1, 0, 0];
  let u = cross(r, f);
  if (pose.roll) { const a = (pose.roll * Math.PI) / 180, c = Math.cos(a), s = Math.sin(a); const r2 = add(r.map((v) => v * c), u.map((v) => v * s)); const u2 = add(u.map((v) => v * c), r.map((v) => -v * s)); r = r2; u = u2; }
  const back = f.map((v) => -v);
  return { location: eye, quaternion: quatFromBasis(r, u, back) };
}

/** Python script that rebuilds proxies, stand-ins, cameras (with sampled animation) in Blender. */
export function toBlenderScript(scene, opts = {}) {
  const fps = opts.fps || 24, gap = opts.gapFrames ?? 12;
  const L = [];
  L.push('# Generated by Layout Studio — rebuilds the blockout, stand-ins and shot cameras.');
  L.push('# Units: metres. Coordinates converted from Y-up (viewer) to Blender Z-up.');
  L.push('import bpy, math');
  L.push('from mathutils import Matrix, Vector, Quaternion');
  L.push(`SCENE_NAME = ${pyName((scene.project || 'Layout') + ' sc' + ((scene.scene || {}).number ?? ''))}`);
  L.push(`FPS = ${fps}`);
  L.push('scn = bpy.context.scene');
  L.push('scn.render.fps = FPS');
  L.push('scn.unit_settings.system = "METRIC"');
  L.push('def coll(name):');
  L.push('    c = bpy.data.collections.get(name)');
  L.push('    if not c:');
  L.push('        c = bpy.data.collections.new(name); scn.collection.children.link(c)');
  L.push('    return c');
  L.push('def mat(name, rgb):');
  L.push('    m = bpy.data.materials.get(name)');
  L.push('    if not m:');
  L.push('        m = bpy.data.materials.new(name); m.diffuse_color = (rgb[0], rgb[1], rgb[2], 1.0)');
  L.push('    return m');
  L.push('def link(obj, c):');
  L.push('    for oc in list(obj.users_collection): oc.objects.unlink(obj)');
  L.push('    c.objects.link(obj)');
  L.push('def prim(kind, name, loc, rot3, size, c, m):');
  L.push('    if kind == "sphere": bpy.ops.mesh.primitive_uv_sphere_add(radius=0.5, segments=16, ring_count=8)');
  L.push('    elif kind == "cylinder": bpy.ops.mesh.primitive_cylinder_add(radius=0.5, depth=1.0, vertices=24)');
  L.push('    elif kind == "cone": bpy.ops.mesh.primitive_cone_add(radius1=0.5, radius2=0.0, depth=1.0, vertices=24)');
  L.push('    else: bpy.ops.mesh.primitive_cube_add(size=1.0)');
  L.push('    o = bpy.context.active_object; o.name = name');
  L.push('    o.matrix_world = Matrix.Translation(Vector(loc)) @ rot3.to_4x4() @ Matrix.Diagonal((size[0], size[1], size[2], 1.0))');
  L.push('    if m: o.data.materials.append(m)');
  L.push('    link(o, c); return o');
  L.push('');
  const ground = coll => coll;
  const envC = 'ENV', propC = 'PROPS', charC = 'CHARACTERS', camC = 'CAMERAS';
  L.push(`c_env, c_prop, c_char, c_cam = coll(${pyName(envC)}), coll(${pyName(propC)}), coll(${pyName(charC)}), coll(${pyName(camC)})`);
  // ground
  const g = scene.world && scene.world.ground;
  if (g) {
    L.push(`bpy.ops.mesh.primitive_plane_add(size=${(g.size || 100).toFixed(2)}); _g = bpy.context.active_object; _g.name = "GROUND"; _g.data.materials.append(mat("M_ground", ${py(hexToRGB(g.color))})); link(_g, c_env)`);
  }
  // first beat blocking as rest state
  const firstShot = (scene.shots || [])[0];
  const restBlocking = firstShot ? blockingFor(scene, firstShot) : ((scene.beats || [])[0] || {}).blocking || {};
  const objects = applyBlocking(scene, restBlocking);
  for (const o of objects) {
    if (o.kind === 'plane' || o.visible === false) continue;
    const rgb = py(hexToRGB(o.color));
    const target = o.kind === 'standin' ? 'c_char' : (o.role === 'PROP' || o.role === 'HERO') ? 'c_prop' : 'c_env';
    if (o.kind === 'standin') {
      const ch = { position: o.position, facing: (o.rotation || [0, 0, 0])[1], pose: o.pose || 'stand', height: o.height || 1.75, age: o.age };
      L.push(`# ${o.name || o.id} (${poseKey(ch.pose)}, ${ch.height} m${o.age != null ? `, ${o.age} y` : ''}) — mannequin`);
      L.push(`root = bpy.data.objects.new(${pyName(o.id)}, None); root.empty_display_type = "PLAIN_AXES"; root.empty_display_size = 0.3; c_char.objects.link(root)`);
      L.push(`root.matrix_world = Matrix.Translation(Vector(${py(C(o.position))})) @ ${pyMat3(toBlenderRot(eulerXYZToMat3(0, ch.facing, 0)).map((r) => r.map((v) => +v.toFixed(6))))}.to_4x4()`);
      L.push(`m_ = mat(${pyName('M_' + o.id)}, ${rgb}); mj_ = mat("M_mannequin_joint", (0.165, 0.18, 0.21)); ma_ = mat(${pyName('M_' + o.id + '_accent')}, ${py(hexToRGB(o.color).map((v) => v * 0.72))})`);
      for (const part of standinParts(ch.pose, ch.height, ch.age)) {
        const kind = part.kind === 'box' ? 'cube' : part.kind === 'capsule' ? 'cylinder' : 'sphere';
        const size = part.kind === 'capsule' ? [part.radius * 2, part.length, part.radius * 2] : part.size;
        const bsize = [size[0], size[2], size[1]];
        const Rb = toBlenderRot(part.m).map((r) => r.map((v) => +v.toFixed(6)));
        const mv = part.mat === 'joint' ? 'mj_' : part.mat === 'accent' ? 'ma_' : 'm_';
        L.push(`p_ = prim("${kind}", ${pyName(o.id + '_' + part.tag)}, ${py(C(part.center))}, ${pyMat3(Rb)}, ${py(bsize)}, c_char, ${mv}); p_.parent = root; p_.matrix_parent_inverse = Matrix.Identity(4)`);
      }
      continue;
    }
    const parts = objectParts(o);
    const R = eulerXYZToMat3(...(o.rotation || [0, 0, 0]));
    const Rb = toBlenderRot(R).map((r) => r.map((v) => +v.toFixed(6)));
    const s = o.scale || [1, 1, 1];
    const kindMap = { sphere: 'sphere', cylinder: 'cylinder', cone: 'cone', capsule: 'cylinder' };
    parts.forEach((part, i) => {
      const kind = o.kind === 'tree' ? (part.tag === 'trunk' ? 'cylinder' : 'cone') : (kindMap[o.kind] || 'cube');
      const worldCenter = add(o.position, mat3MulVec(R, [part.center[0] * s[0], part.center[1] * s[1], part.center[2] * s[2]]));
      const size = [part.size[0] * s[0], part.size[1] * s[1], part.size[2] * s[2]];
      const bsize = [size[0], size[2], size[1]];
      L.push(`prim("${kind}", ${pyName(parts.length > 1 ? `${o.id}_${part.tag || i}` : o.id)}, ${py(C(worldCenter))}, ${pyMat3(Rb)}, ${py(bsize)}, ${target}, mat(${pyName('M_' + (o.color || 'grey').replace('#', ''))}, ${rgb}))`);
    });
  }
  // cameras
  L.push('');
  L.push('def add_cam(name, sensor_w, sensor_h, lens, res_x, res_y):');
  L.push('    cd = bpy.data.cameras.new(name); cd.sensor_fit = "HORIZONTAL"; cd.sensor_width = sensor_w; cd.sensor_height = sensor_h; cd.lens = lens');
  L.push('    o = bpy.data.objects.new(name, cd); o.rotation_mode = "QUATERNION"; c_cam.objects.link(o); return o');
  L.push('def key_cam(o, f, loc, q):');
  L.push('    o.location = loc; o.rotation_quaternion = q');
  L.push('    o.keyframe_insert("location", frame=f); o.keyframe_insert("rotation_quaternion", frame=f)');
  let frame = 1;
  const resX = 2048;
  for (const shot of scene.shots || []) {
    const cam = Object.assign({ filmback: 'ALEXA35_OG', focal_mm: 35, aspect: 2.39, squeeze: 1 }, shot.camera || {});
    const { gate } = fovFor(cam);
    const blocking = blockingFor(scene, shot);
    const subject = resolveSubject(scene, shot, blocking);
    const solved = solveShot(scene, shot);
    const n = Math.max(1, Math.round((shot.duration_s || 4) * fps));
    const resY = Math.round(resX / cam.aspect);
    const name = `CAM_${shot.name || shot.id}`.replace(/[^A-Za-z0-9_.-]/g, '_');
    L.push(`# shot ${shot.name || shot.id}: ${shot.size || ''} ${subject ? subject.name : ''} — ${lensLabel(cam)} — ${describeMove(solved.info)}`);
    L.push(`cam = add_cam(${pyName(name)}, ${gate.w.toFixed(3)}, ${gate.h.toFixed(3)}, ${cam.focal_mm}, ${resX}, ${resY})`);
    if (cam.focus_m) L.push(`cam.data.dof.use_dof = True; cam.data.dof.focus_distance = ${cam.focus_m}; cam.data.dof.aperture_fstop = ${cam.fstop || 2.8}`);
    let prevQ = null;
    for (let i = 0; i <= n; i += 1) {
      const t = i / n;
      const pb = cameraPoseToBlender(solved.pose(t));
      let q = pb.quaternion;
      if (prevQ && dot([q[0], q[1], q[2]], [prevQ[0], prevQ[1], prevQ[2]]) + q[3] * prevQ[3] < 0) q = q.map((v) => -v);
      prevQ = q;
      L.push(`key_cam(cam, ${frame + i}, ${py(pb.location)}, ${py(q)})`);
    }
    L.push(`mk = scn.timeline_markers.new(${pyName(shot.name || shot.id)}, frame=${frame}); mk.camera = cam`);
    frame += n + gap;
  }
  L.push(`scn.frame_start = 1; scn.frame_end = ${frame}`);
  L.push(`scn.render.resolution_x = ${resX}; scn.render.resolution_y = ${Math.round(resX / (((scene.shots || [])[0] || {}).camera?.aspect || 2.39))}`);
  L.push('if scn.timeline_markers: scn.camera = scn.timeline_markers[0].camera');
  L.push('print("Layout Studio: scene rebuilt")');
  return L.join('\n');
}
